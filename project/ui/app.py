import streamlit as st
import requests

st.image(
    "ui/assets/unir_logo.png",
    width=220
)

st.title(
    "Data GovIA"
)
st.info(
    """
**AI Transparency Notice**

You are interacting with an Artificial Intelligence system developed as part of a  Master's TFM.

The recommendations and analyses generated by this prototype are intended to support decision-making and should not be considered professional or legally binding advice.

Human review and professional judgment are required before making organizational decisions based on the generated results.
"""
)

st.write(
    "Intelligent Decision Support System for Data Governance and Data Management"
)

st.write(
    "Atención: Esta aplicación es un piloto experimental y no debe ser utilizada para decisiones críticas de negocio."
)

user_input = st.text_area(
    "Describe the organization",
    height=250
)

analyze_button = st.button(
    "Analyze"
)

if analyze_button:

    response = requests.post(

        "http://127.0.0.1:8000/analyze",

        json={
            "organization_description":
            user_input
        }

    )

    result = response.json()

    st.write(
        result
    )