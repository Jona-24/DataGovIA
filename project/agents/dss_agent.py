from llm.provider import llm
from models.dss_report import DSSReport


def dss_agent(state):

    print("Running DSS Agent")

    organization_context = state.organization_context

    technology_profile = state.technology_profile

    diagnosis = state.diagnosis

    strategy = state.strategy

    prompt = f"""
    # Role

    You are a senior Data Governance consultant responsible for producing the final executive report of an Intelligent Decision Support System (DSS).

    Your responsibility is to consolidate the outputs generated by previous agents into a clear, professional, and business-oriented report.

    Do not perform additional analysis, diagnosis, or strategy generation. Do not introduce new findings, recommendations, or assumptions beyond the information provided.

    # Task

    Generate a professional Data Governance assessment report based exclusively on the information below.

    # Context

    ## Organization Context

    {organization_context}

    ## Technology Profile

    {technology_profile}

    ## Diagnosis

    {diagnosis}

    ## Strategy

    {strategy}

    # Reasoning Constraints

    - Use only the provided information.
    - Do not invent facts or recommendations.
    - Do not infer information that is not explicitly available.
    - Keep the report consistent with the diagnosis and implementation strategy.
    - Present the information in a professional consulting style.

    # Output

    Generate the report in Markdown format with the following sections:

    1. Executive Summary
    2. Main Findings
    3. Business Impact
    4. Recommendations
    5. Quick Wins
    6. Strategic Actions
    7. Impacted Business Metrics

    Return only the Markdown report.
    """

    response = llm.invoke(
        prompt
    )

    state.final_response = DSSReport(report=response.content)

    return state